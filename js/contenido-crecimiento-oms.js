/** El sexo "no-se"/"sorpresa" no tiene tabla propia: se usa niña como base neutra. */
export function tablaPorSexo(sexo, metrica) {
  const tablas = sexo === "nino" ? TABLAS_OMS.nino : TABLAS_OMS.nina;
  return tablas[metrica];
}

/** Interpola los 5 percentiles en una edad exacta (en meses, 0 a 24). */
export function percentilesEnEdad(tabla, edadMeses) {
  const edad = Math.min(Math.max(edadMeses, 0), 24);
  let anterior = tabla[0];
  let siguiente = tabla[tabla.length - 1];
  for (let i = 0; i < tabla.length - 1; i++) {
    if (edad >= tabla[i].mes && edad <= tabla[i + 1].mes) {
      anterior = tabla[i];
      siguiente = tabla[i + 1];
      break;
    }
  }
  const rango = siguiente.mes - anterior.mes || 1;
  const proporcion = (edad - anterior.mes) / rango;
  const interpolar = (campo) => anterior[campo] + (siguiente[campo] - anterior[campo]) * proporcion;
  return {
    p3: interpolar("p3"),
    p15: interpolar("p15"),
    p50: interpolar("p50"),
    p85: interpolar("p85"),
    p97: interpolar("p97"),
  };
}

/** Clasifica un valor dentro de las franjas de percentiles. */
export function ubicarFranja(valor, percentiles) {
  if (valor < percentiles.p3) return "muyBajo";
  if (valor < percentiles.p15) return "bajo";
  if (valor <= percentiles.p85) return "esperado";
  if (valor <= percentiles.p97) return "alto";
  return "muyAlto";
}
