const REGLAS_SEGURIDAD =
  "Jugá siempre cerca y supervisando. Nada de objetos chicos, bolsas ni cordones al alcance. Elegí juguetes grandes, sin piezas sueltas.";

const CUANDO_CONSULTAR =
  'Cada bebé tiene sus tiempos. Si notás que no se da vuelta ni sostiene la cabeza pasados los 4 meses, no se sienta con apoyo pasados los 9 meses, o no dice ninguna palabra al año, comentalo en el próximo control.';

/** Devuelve el contenido del mes al que "está yendo" el bebé (mes actual + 1, hasta 12). */
export function estimulacionDelMes(mesesCumplidos) {
  const mesObjetivo = Math.min(mesesCumplidos + 1, 12);
  return {
    ...ESTIMULACION_POR_MES.find((m) => m.mes === mesObjetivo),
    reglasSeguridad: REGLAS_SEGURIDAD,
    cuandoConsultar: CUANDO_CONSULTAR,
  };
}
